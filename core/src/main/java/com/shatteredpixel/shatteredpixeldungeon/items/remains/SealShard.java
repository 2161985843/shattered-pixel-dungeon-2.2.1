import com.watabou.utils.Random;

import java.util.ArrayList;

public class SealShard extends RemainsItem {

	{
		image = ItemSpriteSheet.SEAL_SHARD;
	}

	@Override
	protected void doEffect(Hero hero) {
		ArrayList<Integer> spawnPoints = new ArrayList<>();

		for (int i = 0; i < PathFinder.NEIGHBOURS8.length; i++) {
			int p = hero.pos + PathFinder.NEIGHBOURS8[i];
			if (Actor.findChar( p ) == null && Dungeon.level.passable[p]) {
				spawnPoints.add( p );
			}
		}

		int ratsToSpawn = 2;

		while (ratsToSpawn > 0 && spawnPoints.size() > 0) {
			int index = Random.index( spawnPoints );

			Rat rat = new Rat();
			rat.alignment = Char.Alignment.ALLY;
			rat.state = rat.PASSIVE;
			Buff.affect(rat, AscensionChallenge.AscensionBuffBlocker.class);
			GameScene.add( rat );
			ScrollOfTeleportation.appear( rat, spawnPoints.get( index ) );

			spawnPoints.remove( index );
			ratsToSpawn--;
		}
		Buff.affect(hero, Barrier.class).incShield(hero.HT/10);
		Sample.INSTANCE.play(Assets.Sounds.UNLOCK);
	}

}
